'use client';

import { useEffect, useState } from 'react';
import SocialSignIn from '../../../components/SocialSignIn';
import { BACKEND_URL, websiteAuth } from '../../../lib/website-auth';
import styles from './page.module.css';

const date = value => value ? new Date(value).toLocaleDateString('en-AU', { day: 'numeric', month: 'short', year: 'numeric' }) : '';
export default function ArtistAccount() {
  const [session, setSession] = useState(null);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [billing, setBilling] = useState(null);
  const [settings, setSettings] = useState(null);
  const [isArtist, setIsArtist] = useState(null);
  const [busy, setBusy] = useState('');
  const [error, setError] = useState('');
  const [message, setMessage] = useState('');
  const [code, setCode] = useState('');

  async function api(path, method = 'GET', body) {
    const { data } = await websiteAuth().auth.getSession();
    if (!data.session) throw new Error('Please sign in again.');
    const response = await fetch(`${BACKEND_URL}${path}`, {
      method, cache: 'no-store', headers: { Authorization: `Bearer ${data.session.access_token}`, ...(body ? { 'Content-Type': 'application/json' } : {}) },
      ...(body ? { body: JSON.stringify(body) } : {}),
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(result.error || result.message || 'Unable to complete this request. Please try again.');
    return result;
  }
  async function load() {
    const user = await api('/auth/users/me');
    const artist = (user.accountType || user.account_type || '').toLowerCase() === 'artist' || Boolean(user.artistProfile || user.artist_profile);
    setIsArtist(artist);
    if (!artist) { setSettings(null); setBilling(null); return; }
    const [b, s] = await Promise.all([api('/artists/me/notification-subscription'), api('/artists/me/client-notifications')]);
    setBilling(b); setSettings(s);
  }
  useEffect(() => {
    let live = true;
    websiteAuth().auth.getSession().then(({ data }) => { if (live) setSession(data.session); });
    const { data } = websiteAuth().auth.onAuthStateChange((_event, value) => { if (live) setSession(value); });
    const params = new URLSearchParams(location.search);
    if (params.get('checkout') === 'success') setMessage('Checkout completed. Your subscription will appear after payment is verified. Refresh to check its status.');
    if (params.get('checkout') === 'cancelled') setMessage('Checkout cancelled. Your current access is unchanged.');
    if (params.has('mailbox')) setMessage(params.get('mailbox') === 'connected' ? 'Mailbox connected. Choose it as your email sender below and save.' : 'Mailbox connection was not completed. You can try again below.');
    return () => { live = false; data.subscription.unsubscribe(); };
  }, []);
  useEffect(() => {
    if (session) { setBusy('load');
      const refresh = async () => {
        if (new URLSearchParams(location.search).get('checkout') === 'cancelled') {
          await api('/artists/me/notification-subscription/cancel-checkout', 'POST');
          history.replaceState({}, '', '/artist/account');
        }
        await load();
      };
      refresh().catch(e => setError(e.message)).finally(() => setBusy(''));
    }
    else { setBilling(null); setSettings(null); setIsArtist(null); }
  }, [session?.user?.id]);
  async function run(name, work) {
    setBusy(name); setError(''); setMessage('');
    try { await work(); } catch (e) { setError(e.message); } finally { setBusy(''); }
  }
  async function login(event) {
    event.preventDefault();
    await run('login', async () => { const result = await websiteAuth().auth.signInWithPassword({ email, password }); if (result.error) throw result.error; setSession(result.data.session); });
  }
  async function navigate(path) {
    const result = await api(path, 'POST');
    // URLs are generated by the backend; never accept a return URL from the query string.
    const destination = new URL(result.url);
    if (destination.protocol !== 'https:') throw new Error('Unable to open this page.');
    location.assign(destination.href);
  }
  async function save(event) {
    event.preventDefault();
    await run('save', async () => {
      const body = { send_confirmation_email: settings.send_confirmation_email };
      if (billing.entitled) Object.assign(body, {
        custom_email_provider: settings.custom_email_provider,
        send_sms_reminder: settings.send_sms_reminder,
        send_reminder_7d: settings.send_reminder_7d,
        send_reminder_24h: settings.send_reminder_24h,
        notification_timezone: settings.notification_timezone,
      });
      setSettings(await api('/artists/me/client-notifications', 'PUT', body)); setMessage('Notification settings saved.');
    });
  }
  const update = (key, value) => setSettings(s => ({ ...s, [key]: value }));
  const entitled = Boolean(billing?.entitled);
  const account = billing?.account || {};
  return <main className={styles.page}><div className={styles.content}>
    <a href="/" className={styles.back}>← Vanta</a>
    <h1>Artist account</h1><p className={styles.intro}>Client emails, reminders and your notification subscription.</p>
    {error && <p role="alert" className={styles.error}>{error}</p>}
    {message && <p role="status" className={styles.message}>{message}</p>}
    {!session ? <section className={styles.card}><h2>Sign in to your artist account</h2>
      <form onSubmit={login} className={styles.form}>
        <label>Email<input type="email" autoComplete="email" value={email} onChange={e => setEmail(e.target.value)} required /></label>
        <label>Password<input type="password" autoComplete="current-password" value={password} onChange={e => setPassword(e.target.value)} required /></label>
        <button disabled={Boolean(busy)}>Sign in</button>
      </form><SocialSignIn disabled={Boolean(busy)} />
      <p className={styles.help}>Use the same account as the Vanta artist app.</p>
    </section> : <>
      <div className={styles.session}><span>{session.user?.email}</span><button disabled={Boolean(busy)} onClick={() => run('logout', () => websiteAuth().auth.signOut())}>Sign out</button></div>
      {isArtist === false && <section className={styles.card}><h2>An artist account is needed</h2><p>Switch to an artist account in the Vanta app, then return here.</p></section>}
      {isArtist !== false && <>
        <section className={styles.card}><div className={styles.row}><h2>Client notifications</h2><button disabled={Boolean(busy)} onClick={() => run('refresh', load)}>Refresh</button></div>
          {billing ? <>
            <p className={styles.price}>A$4.99 <span>/ month</span></p>
            <p>Includes Gmail or Outlook sending, SMS reminders, and reminder emails 7 days and 24 hours before appointments.</p>
            <p className={styles.status}>{entitled ? 'Paid features active' : 'Free plan — confirmation emails included'}</p>
            {account.free_until && new Date(account.free_until) > new Date() && <p>Free access through {date(account.free_until)}.</p>}
            {billing.has_subscription && <p>{account.cancel_at_period_end ? 'Subscription ends' : account.status === 'trialing' ? 'First payment due' : 'Current billing period ends'} {date(account.paid_until)}. Status: {account.status}.</p>}
            {billing.has_subscription ? <button disabled={Boolean(busy)} onClick={() => run('portal', () => navigate('/artists/me/notification-subscription/portal'))}>Manage billing or cancel</button> : <>
              <button disabled={Boolean(busy) || !billing.checkout_available || billing.pending_redemption} onClick={() => run('checkout', () => navigate('/artists/me/notification-subscription/checkout'))}>Subscribe for A$4.99/month</button>
              {!billing.checkout_available && <p className={styles.help}>Subscription checkout is not available yet. You can still redeem a free-month code.</p>}
              <p className={styles.help}>Renews monthly until cancelled. If you have free access, your first charge follows that period. Card details are collected by Stripe.</p>
            </>}
          </> : <p>Loading account…</p>}
        </section>
        <section className={styles.card}><h2>Redeem free months</h2><p>Have a Vanta code? Redeem it on this artist account. No card is needed for free access.</p>
          <form className={styles.form} onSubmit={event => { event.preventDefault(); run('redeem', async () => {
            const result = await api('/artists/me/notification-subscription/redeem', 'POST', { code: code.trim() });
            setCode(''); await load(); setMessage(`${result.months} free month${result.months === 1 ? '' : 's'} applied. Access through ${date(result.access_until)}.`);
          }); }}><label>Code<input value={code} onChange={e => setCode(e.target.value)} autoComplete="off" maxLength={128} required /></label><button disabled={Boolean(busy) || !code.trim()}>Redeem code</button></form>
          <p className={styles.help}>Each code can be used once per artist. For an existing subscription, free months move the next payment date forward. If a redemption is interrupted, retry the same code.</p>
          {billing?.pending_redemption && <p role="status">A code is waiting to finish. Re-enter the same code to retry before starting checkout.</p>}
        </section>
        {settings && <form onSubmit={save} className={styles.card}>
          <div className={styles.row}><h2>Delivery preferences</h2><button disabled={Boolean(busy)}>Save settings</button></div>
          <label className={styles.toggle}><input type="checkbox" checked={settings.send_confirmation_email} onChange={e => update('send_confirmation_email', e.target.checked)} disabled={Boolean(busy)} /><span><strong>Confirmation email · Free</strong><small>Automatically email clients when their booking is confirmed.</small></span></label>
          <fieldset disabled={!entitled || Boolean(busy)}><legend>Paid features{!entitled ? ' · Locked' : ''}</legend>
            <label>Email sender<select value={settings.custom_email_provider} onChange={e => update('custom_email_provider', e.target.value)}><option value="vanta">Vanta</option>{['gmail', 'outlook'].map(provider => <option key={provider} value={provider} disabled={!settings.connections?.some(c => c.provider === provider)}>{provider === 'gmail' ? 'Gmail' : 'Outlook'}</option>)}</select></label>
            <div className={styles.connections}>{['gmail', 'outlook'].map(provider => {
              const connection = settings.connections?.find(c => c.provider === provider);
              return <div key={provider}><p>{provider === 'gmail' ? 'Gmail' : 'Outlook'}{connection ? `: ${connection.email}` : ''}</p>
                {connection ? <button type="button" onClick={() => run('disconnect', async () => { await api(`/artists/me/notification-mailbox/${provider}`, 'DELETE'); await load(); })}>Disconnect</button>
                  : <button type="button" disabled={!settings.providers?.[provider]} onClick={() => run('connect', () => navigate(`/artists/me/notification-mailbox/${provider}`))}>Connect {provider === 'gmail' ? 'Gmail' : 'Outlook'}</button>}
                {!connection && !settings.providers?.[provider] && <small>Connection not available yet.</small>}
              </div>;
            })}</div>
            <label className={styles.toggle}><input type="checkbox" checked={settings.send_reminder_7d} onChange={e => update('send_reminder_7d', e.target.checked)} /><span>7-day email reminder</span></label>
            <label className={styles.toggle}><input type="checkbox" checked={settings.send_reminder_24h} onChange={e => update('send_reminder_24h', e.target.checked)} /><span>24-hour email reminder</span></label>
            <label className={styles.toggle}><input type="checkbox" checked={settings.send_sms_reminder} disabled={!settings.sms_available} onChange={e => update('send_sms_reminder', e.target.checked)} /><span>24-hour SMS reminder<small>Only sent to clients who consented to SMS reminders.{!settings.sms_available && ' SMS delivery is not available yet.'}</small></span></label>
            <label>Appointment time zone<input value={settings.notification_timezone} onChange={e => update('notification_timezone', e.target.value)} placeholder="Australia/Sydney" required /></label>
          </fieldset>
          <p className={styles.help}>Studio appointments use your studio’s reminder settings. A disconnected sender must be reconnected or switched to Vanta. If paid access expires, confirmation emails use Vanta and paid reminders stop.</p>
        </form>}
      </>}
    </>}
  </div></main>;
}
